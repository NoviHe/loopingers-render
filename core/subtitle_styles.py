"""
Subtitle and Karaoke Styling module for Advanced SubStation Alpha (.ass) format.
"""

def hex_to_ass_color(hex_str: str, alpha: int = 0) -> str:
    """
    Converts '#RRGGBB' or 'RRGGBB' to ASS color format '&HAABBGGRR&'.
    Alpha: 0 = fully opaque, 255 = fully transparent.
    """
    clean_hex = hex_str.lstrip('#')
    if len(clean_hex) == 3:
        clean_hex = ''.join([c*2 for c in clean_hex])
    if len(clean_hex) != 6:
        clean_hex = "FFFFFF"

    r = clean_hex[0:2]
    g = clean_hex[2:4]
    b = clean_hex[4:6]
    a = f"{alpha:02X}"
    return f"&H{a}{b}{g}{r}&"


