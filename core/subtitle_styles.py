def build_ass_header(
    width: int = 1920,
    height: int = 1080,
    font_name: str = "Arial",
    font_size: int = 48,
    normal_color: str = "#FFFFFF",
    singing_color: str = "#FFD700",
    outline_color: str = "#000000",
    shadow_color: str = "#000000",
    outline_width: float = 3.0,
    shadow_depth: float = 2.0,
    alignment: int = 2,  # 2 = Bottom Center, 8 = Top Center, 5 = Middle Center
    margin_v: int = 70,
    title_banner: bool = True
) -> str:
    """
    Generates ASS script header and styles.
    """
    ass_primary = hex_to_ass_color(normal_color)
    ass_secondary = hex_to_ass_color(singing_color)
    ass_outline = hex_to_ass_color(outline_color)
    ass_back = hex_to_ass_color(shadow_color, alpha=100)

    # Title card styling
    title_primary = hex_to_ass_color("#FFFFFF")
    title_secondary = hex_to_ass_color(singing_color)

    header = f"""[Script Info]
; Script generated by LoopKaraoke Studio
Title: LoopKaraoke Video
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: {width}
PlayResY: {height}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Karaoke,{font_name},{font_size},{ass_primary},{ass_secondary},{ass_outline},{ass_back},-1,0,0,0,100,100,1,0,1,{outline_width},{shadow_depth},{alignment},30,30,{margin_v},1
Style: KaraokeActive,{font_name},{int(font_size * 1.05)},{ass_secondary},{ass_secondary},{ass_outline},{ass_back},-1,0,0,0,100,100,1,0,1,{outline_width},{shadow_depth},{alignment},30,30,{margin_v},1
Style: SongTitle,{font_name},{int(font_size * 0.9)},{title_primary},{title_secondary},{ass_outline},{ass_back},-1,0,0,0,100,100,1,0,1,2,2,7,50,50,50,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    return header
